      doc.setTextColor(255, 255, 255);
      doc.setFont('helvetica', 'bold');
      doc.setFontSize(8);
      doc.text(`MANIFEST INDEX CONTINUED - ${truck.type.toUpperCase()} #${truck.truckNumber}`, 15, 9);
      

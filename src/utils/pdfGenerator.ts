/**
 * Formats a component description for PDF reports with unit designation ("/1", "/2", etc.)
 * e.g., "HV Bushing /1", "Main Conservator /2", "Radiator Bank A /1 (Rotated 90°)"
 */
export function getComponentDescriptionWithUnit(item: TransformerItem, rotated = false): string {
  let name = item.componentName ? item.componentName.trim() : '';

  // If the name already ends with /<digit>, avoid appending duplicate unit designation
  if (!/\/\s*\d+$/.test(name)) {
    let unitNum = '';

    // 1. Try extracting from projectCode: e.g. "PT0512/1", "PT0512/2", "P101 / 3", "PT0512-2"
    if (item.projectCode) {
      const matchSlash = item.projectCode.match(/\/\s*(?:Unit\s*|U\s*)?(\d+)/i);
      if (matchSlash && matchSlash[1]) {
        unitNum = matchSlash[1];
      } else {
        const matchDash = item.projectCode.match(/[-_]\s*(?:Unit\s*|U\s*)?(\d+)$/i);
        if (matchDash && matchDash[1]) {
          unitNum = matchDash[1];
        }
      }
    }

    // 2. Try extracting from item.id if generated by excel duplicate function (e.g. "box-2-...")
    if (!unitNum && item.id) {
      const matchId = item.id.match(/^box-(\d+)-/);
      if (matchId && matchId[1]) {
        unitNum = matchId[1];
      }
    }

    // 3. Fallback: default to unit 1
    if (!unitNum) {
      unitNum = '1';
    }

    name = `${name} /${unitNum}`;
  }

  if (rotated) {
    name += ' (Rotated 90°)';
  }

  return name;
}

/**
 * Generates a clean, professional PDF report of the Truck Loading Plan
 * Custom layout settings:
 * - Section 1: Summary Dashboard
 * - Section 2: Flat Bed Loading Plan (2 trucks per page)
 * - Section 3: Low Bed / ODC Loading Plan (1 truck per page)
 * - Section 4: Unassigned / Review Required Items (if any)
 */
export function generateLoadingPlanPDF(
  trucks: Truck[],
  unpackedItems: TransformerItem[],
  totalWeight: number,
  globalEfficiency: number,
  payloadCapacity: number,
  exportMode: 'flatbed' | 'lowbed' | 'complete' = 'complete',
  aiInsights: any[] = []
): jsPDF {
  const doc = new jsPDF({
    orientation: 'portrait',
    unit: 'mm',
    format: 'a4',
  });

  const pageHeight = doc.internal.pageSize.getHeight();
  const pageWidth = doc.internal.pageSize.getWidth();
  let pageNum = 1;

  // Header and Footer draw utility
  const drawPageHeader = (title: string, pNum: number) => {
    // Dark professional header banner
    doc.setFillColor(15, 23, 42); // Primary Deep Slate
    doc.rect(0, 0, pageWidth, 25, 'F');

    // Voltamp orange/amber highlighting line
    doc.setFillColor(249, 115, 22); // Amber Accent
    doc.rect(0, 25, pageWidth, 1.5, 'F');

    // Left side of the header: company name bold, professional and vertically centered
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(11);
    doc.setTextColor(255, 255, 255);
    doc.text('VOLTAMP POWER TRANSFORMERS', 15, 14.5);

    // Right-aligned branding metadata
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(10);
    doc.setTextColor(255, 255, 255);
    doc.text('Transformer Truck Loading Plan', pageWidth - 15, 8.5, { align: 'right' });

    // Dynamic active Project Codes
    const activeProjects = Array.from(new Set(targetTrucks.flatMap(t => t.items.map(pi => pi.item.projectCode)))).filter(Boolean);
    const projectText = activeProjects.length > 0 ? `${activeProjects.join(', ')}` : 'MULTI-SYSTEM';
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(7);
    doc.setTextColor(203, 213, 225);
    doc.text(`Project Code: ${projectText}`.substring(0, 48), pageWidth - 15, 13, { align: 'right' });

    // Report Date
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(7);
    doc.setTextColor(148, 163, 184);
    doc.text(`Report Date: ${new Date().toLocaleDateString()}`, pageWidth - 15, 17.5, { align: 'right' });

    // Section title
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(7.5);
    doc.setTextColor(249, 115, 22); // Amber highlighted segment title
    doc.text(title.toUpperCase(), pageWidth - 15, 22.5, { align: 'right' });
    
    // Page footer bottom
    doc.setDrawColor(226, 232, 240);
    doc.setLineWidth(0.3);
    doc.line(15, pageHeight - 15, pageWidth - 15, pageHeight - 15);

    doc.setFont('helvetica', 'normal');
    doc.setFontSize(7.5);
    doc.setTextColor(100, 116, 139);
    doc.text(`Generated on: ${new Date().toLocaleDateString()} ${new Date().toLocaleTimeString()}  |  Confidential Logistics Report`, 15, pageHeight - 10);
    doc.text(`Page ${pNum}`, pageWidth - 15, pageHeight - 10, { align: 'right' });
  };

  // Filter trucks based on the requested export mode
  const targetTrucks = trucks.filter(t => {
    if (exportMode === 'flatbed') return t.type !== 'Low Bed';
    if (exportMode === 'lowbed') return t.type === 'Low Bed';
    return true; // Complete / Coordinated plan
  });

  // Calculate stats specifically for the target trucks in this PDF
  const totalTrucksCount = targetTrucks.length;
  const omanTrucksCount = targetTrucks.filter(t => t.originGroup === 'Oman').length;
  const importedTrucksCount = targetTrucks.filter(t => t.originGroup === 'Imported').length;
  const lowBedTrucksCount = targetTrucks.filter(t => t.type === 'Low Bed').length;
  const flatBedCount = targetTrucks.filter(t => t.type !== 'Low Bed').length;
  const nonLowBedTypeName = targetTrucks.find(t => t.type !== 'Low Bed')?.type || 'Flat Bed';
  
  const selectedTotalWeight = targetTrucks.reduce((sum, t) => sum + t.items.reduce((sum, pi) => sum + pi.item.weight, 0), 0);
  
  // Calculate specific floor efficiency for selected trucks
  let selectedAvgEfficiency = 0;
  if (targetTrucks.length > 0) {
    const totalOccupancy = targetTrucks.reduce((sum, t) => {
      const usedArea = t.items.reduce((aSum, pi) => aSum + (pi.w * pi.l), 0);
      const totalArea = t.lengthLimit * t.widthLimit;
      return sum + (usedArea / totalArea);
    }, 0);
    selectedAvgEfficiency = (totalOccupancy / targetTrucks.length) * 100;
  }

  // ================= SECTION 1: SUMMARY DASHBOARD =================
  drawPageHeader(`SECTION 1: LOGISTICS REGISTER (${exportMode.toUpperCase()})`, pageNum);

  let currentY = 38;

  // Title block
  doc.setTextColor(15, 23, 42);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(16);
  if (exportMode === 'flatbed') {
    doc.text(`${nonLowBedTypeName.toUpperCase()} DISPATCH LOADING REGISTER`, 15, currentY);
  } else if (exportMode === 'lowbed') {
    doc.text('LOW BED / ODC HEAVY ESCORT ROUTE REGISTER', 15, currentY);
  } else {
    doc.text('COMPLETE MULTI-CARRIER CLEARANCE PLAN', 15, currentY);
  }
  currentY += 6;

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(9);
  doc.setTextColor(71, 85, 105);
  doc.text('Standard multi-attribute clearance & dimensional verification statement for transport authorization.', 15, currentY);
  currentY += 10;

  // Stats cards rendering helper
  const drawStatCard = (x: number, y: number, w: number, h: number, title: string, val: string, subText: string, color: [number, number, number]) => {
    doc.setFillColor(248, 250, 252);
    doc.roundedRect(x, y, w, h, 1.5, 1.5, 'F');
    doc.setDrawColor(226, 232, 240);
    doc.setLineWidth(0.35);
    doc.roundedRect(x, y, w, h, 1.5, 1.5, 'S');

    doc.setFillColor(color[0], color[1], color[2]);
    doc.rect(x, y, 2.5, h, 'F'); // left accent border

    doc.setFont('helvetica', 'bold');
    doc.setFontSize(7.5);
    doc.setTextColor(100, 116, 139);
    doc.text(title.toUpperCase(), x + 6, y + 6);

    doc.setFont('helvetica', 'bold');
    doc.setFontSize(13);
    doc.setTextColor(15, 23, 42);
    doc.text(val, x + 6, y + 14);

    doc.setFont('helvetica', 'normal');
    doc.setFontSize(7);
    doc.setTextColor(148, 163, 184);
    doc.text(subText, x + 6, y + 20);
  };

  const cardW = 55;
  const cardH = 24;

  const carrierSubText = lowBedTrucksCount === 0
    ? `${flatBedCount} ${nonLowBedTypeName} (Flat Bed Only)`
    : flatBedCount === 0
    ? `${lowBedTrucksCount} Low Bed (Low Bed Only)`
    : `${flatBedCount} ${nonLowBedTypeName === 'Flat Bed' ? 'Flatb.' : 'Cont.'} | ${lowBedTrucksCount} Lowb.`;

  // Row 1 cards
  drawStatCard(15, currentY, cardW, cardH, 'Required Rig Carriers', `${totalTrucksCount} Trucks`, carrierSubText, [14, 165, 233]);
  drawStatCard(15 + cardW + 8, currentY, cardW, cardH, 'Cumulative Mass', `${(selectedTotalWeight / 1000).toFixed(2)} Tons`, `${selectedTotalWeight.toLocaleString()} kg total`, [34, 197, 94]);
  drawStatCard(15 + (cardW + 8) * 2, currentY, cardW, cardH, 'Staging Efficiency', `${selectedAvgEfficiency.toFixed(1)}%`, 'Average bed usage', [168, 85, 247]);

  currentY += cardH + 11;

  // Section heading for Allocation Index table
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(10.5);
  doc.setTextColor(15, 23, 42);
  doc.text('STAGING FLEET DESPATCH ALLOCATION INDEX', 15, currentY);
  currentY += 5;

  // Allocation table headers
  const colWidths = [20, 30, 45, 20, 25, 20, 20];
  const tableHeaders = ['TRUCK ID', 'TRUCK TYPE', 'CARGO ORIGIN', 'LOAD COUNT', 'TOTAL WEIGHT', 'BED USED %', 'BG SPACE %'];
  
  doc.setFillColor(71, 85, 105);
  doc.rect(15, currentY, pageWidth - 30, 6, 'F');
  
  doc.setTextColor(255, 255, 255);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(7);
  let curTableX = 15;
  for (let colIdx = 0; colIdx < tableHeaders.length; colIdx++) {
    doc.text(tableHeaders[colIdx], curTableX + 2, currentY + 4.2);
    curTableX += colWidths[colIdx];
  }
  currentY += 6;

  // Draw table contents rows
  if (targetTrucks.length === 0) {
    doc.setFont('helvetica', 'italic');
    doc.setFontSize(8);
    doc.setTextColor(148, 163, 184);
    doc.text('No active truck configurations matching this criteria found.', 20, currentY + 6);
    currentY += 12;
  } else {
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(7.5);
    doc.setTextColor(15, 23, 42);

    for (let tIdx = 0; tIdx < targetTrucks.length; tIdx++) {
      const truck = targetTrucks[tIdx];
      curTableX = 15;

      const originText = getTruckOriginLabel(truck);
      const wrappedOrigin = doc.splitTextToSize(originText, colWidths[2] - 4);
      const lineCount = wrappedOrigin.length;
      const rowHeight = Math.max(5.5, lineCount * 2.8 + 1.2);

      // zebra striping
      if (tIdx % 2 === 1) {
        doc.setFillColor(248, 250, 252);
        doc.rect(15, currentY, pageWidth - 30, rowHeight, 'F');
      }

      doc.setDrawColor(226, 232, 240);
      doc.setLineWidth(0.15);
      doc.line(15, currentY + rowHeight, pageWidth - 15, currentY + rowHeight);

      const tWt = truck.items.reduce((sum, pi) => sum + pi.item.weight, 0);
      const uAreaSqM = truck.items.reduce((sum, pi) => sum + (pi.w * pi.l), 0) / 1000000;
      const tAreaSqM = (truck.lengthLimit * truck.widthLimit) / 1000000;
      const usedPercent = Math.min(100, (uAreaSqM / tAreaSqM) * 100);
      const remPercent = 100 - usedPercent;

      const isLowBed = truck.type === 'Low Bed';
      const isContainer = truck.type === '40ft HC Container';
      const rowValues = [
        isLowBed ? `LB#${truck.truckNumber}` : (isContainer ? `HC#${truck.truckNumber}` : `FB#${truck.truckNumber}`),
        isLowBed ? 'Low Bed (Heavy)' : (isContainer ? '40ft HC Container' : 'Flat Bed Logistic'),
        '', // Rendered via wrappedOrigin logic
        `${truck.items.length} pcs`,
        `${tWt.toLocaleString()} kg`,
        `${usedPercent.toFixed(1)}%`,
        `${remPercent.toFixed(1)}%`
      ];

      for (let cIdx = 0; cIdx < rowValues.length; cIdx++) {
        if (cIdx === 2) {
          // Centered line wrapping for Cargo Origin
          const textHeight = lineCount * 2.8 - 0.8;
          const yStart = currentY + (rowHeight - textHeight) / 2 + 1.9;
          for (let l = 0; l < lineCount; l++) {
            doc.text(wrappedOrigin[l], curTableX + 2, yStart + l * 2.8);
          }
        } else {
          // Single-line vertical centering
          const verticalAdjustment = (rowHeight - 5.5) / 2;
          doc.text(rowValues[cIdx], curTableX + 2, currentY + 3.7 + verticalAdjustment);
        }
        curTableX += colWidths[cIdx];
      }
      currentY += rowHeight;

      if (currentY > pageHeight - 45) {
        // Table safety break
        break;
      }
    }
  }

  // Draw unpacked/quarantined accessories warning at the bottom
  const eligibleUnpacked = exportMode === 'lowbed' ? [] : unpackedItems;
  if (eligibleUnpacked.length > 0) {
    currentY += 6;
    doc.setFillColor(254, 242, 242); // deep warn red
    doc.roundedRect(15, currentY, pageWidth - 30, 16, 1, 1, 'F');
    doc.setDrawColor(248, 113, 113);
    doc.setLineWidth(0.4);
    doc.roundedRect(15, currentY, pageWidth - 30, 16, 1, 1, 'S');

    doc.setFont('helvetica', 'bold');
    doc.setFontSize(7.5);
    doc.setTextColor(153, 27, 27);
    doc.text('ATTENTION: ACCESSORY SHIFT DETECTED - QUARANTINE ITEMS REQUIRED REVIEW', 18, currentY + 4.5);

    doc.setFont('helvetica', 'normal');
    doc.setFontSize(7);
    doc.setTextColor(185, 28, 28);
    const itemListStr = eligibleUnpacked.map(item => `${getComponentDescriptionWithUnit(item)} (${item.length}x${item.width})`).join(', ');
    const displayStr = `The following ${eligibleUnpacked.length} components exceed standard ${nonLowBedTypeName.toLowerCase()} dimensional layouts even when rotated: ` + itemListStr;
    doc.text(displayStr.substring(0, 125) + (displayStr.length > 125 ? '...' : ''), 18, currentY + 9);
    doc.text('Go to Section 4 on the last page of the complete report to review details.', 18, currentY + 13);
  }


  // ================= SECTION 2: FLAT BED TRUCKS LOADING PLANS (1 per page) =================
  if (exportMode === 'complete' || exportMode === 'flatbed') {
    const flatBedTrucksList = targetTrucks.filter(t => t.type !== 'Low Bed');
    
    for (let tIdx = 0; tIdx < flatBedTrucksList.length; tIdx++) {
      doc.addPage();
      pageNum++;
      
      const truck = flatBedTrucksList[tIdx];
      drawPageHeader(`SECTION 2: ${truck.type.toUpperCase()} LOADING PLAN`, pageNum);
      drawTruckPageContent(doc, truck, aiInsights);
    }
  }


  // ================= SECTION 3: LOW BED / ODC PLANS (1 per page) =================
  if (exportMode === 'complete' || exportMode === 'lowbed') {
    const lowBedTrucksList = targetTrucks.filter(t => t.type === 'Low Bed');

    for (let lIdx = 0; lIdx < lowBedTrucksList.length; lIdx++) {
      doc.addPage();
      pageNum++;

      const truck = lowBedTrucksList[lIdx];
      drawPageHeader('SECTION 3: HEAVY LOW-BED / ODC STAGING', pageNum);
      drawTruckPageContent(doc, truck, aiInsights);
    }
  }


  // ================= SECTION 4: UNASSIGNED ACCESSORIES REVIEW =================
  if ((exportMode === 'complete' || exportMode === 'flatbed') && unpackedItems.length > 0) {
    doc.addPage();
    pageNum++;
    drawPageHeader('SECTION 4: UNRESOLVED / REVIEW NEEDED', pageNum);

    let curY = 32;

    doc.setFillColor(254, 242, 242); // bold dark quarantine background
    doc.roundedRect(15, curY, pageWidth - 30, 18, 1, 1, 'F');
    doc.setDrawColor(239, 68, 68);
    doc.setLineWidth(0.4);
    doc.roundedRect(15, curY, pageWidth - 30, 18, 1, 1, 'S');

    doc.setTextColor(153, 27, 27);
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(10);
    doc.text('UNASSIGNED ACCESSORIES UNDER LOGISTICS DISCREPANCY HOLD', 19, curY + 6);

    doc.setFont('helvetica', 'normal');
    doc.setFontSize(7.5);
    doc.setTextColor(185, 28, 28);
    doc.text(`The components registered below exceed default 2D ${nonLowBedTypeName} clear space dimensions.`, 19, curY + 11.5);
    doc.text(`Manual dispatch review, custom ${nonLowBedTypeName.toLowerCase()} setups or dedicated separate small rigs are required for clearance.`, 19, curY + 15);

    curY += 23;

    // Table listing
    const unassignedColWidths = [15, 30, 65, 35, 20, 15];
    const unassignedHeaders = ['ITEM IND', 'PART CODE', 'COMPONENT DESCRIPTION', 'DIMENSIONS (L x W x H) mm', 'WEIGHT', 'ORIGIN'];

    doc.setFillColor(51, 65, 85);
    doc.rect(15, curY, pageWidth - 30, 5, 'F');

    doc.setTextColor(255, 255, 255);
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(7);
    let uX = 15;
    for (let c = 0; c < unassignedHeaders.length; c++) {
      doc.text(unassignedHeaders[c], uX + 2, curY + 3.8);
      uX += unassignedColWidths[c];
    }
    curY += 5;

    doc.setFont('helvetica', 'normal');
    doc.setFontSize(7.5);
    doc.setTextColor(15, 23, 42);

    for (let uIdx = 0; uIdx < unpackedItems.length; uIdx++) {
      const item = unpackedItems[uIdx];
      uX = 15;

      doc.setFont('helvetica', 'normal');
      doc.setFontSize(7.5);
      const wrappedName = doc.splitTextToSize(getComponentDescriptionWithUnit(item), unassignedColWidths[2] - 4);
      const wrappedProjectCode = doc.splitTextToSize(item.projectCode || '', unassignedColWidths[1] - 4);
      const maxLineCount = Math.max(wrappedName.length, wrappedProjectCode.length);
      const rowHeight = Math.max(4.5, maxLineCount * 2.5 + 1.2);

      if (uIdx % 2 === 1) {
        doc.setFillColor(248, 250, 252);
        doc.rect(15, curY, pageWidth - 30, rowHeight, 'F');
      }

      doc.setDrawColor(226, 232, 240);
      doc.setLineWidth(0.1);
      doc.line(15, curY + rowHeight, pageWidth - 15, curY + rowHeight);

      const cells = [
        `UN-#${uIdx + 1}`,
        '', // Handled below
        '', // Handled below
        `${item.length}×${item.width}×${item.height} mm`,
        `${item.weight.toLocaleString()} kg`,
        item.origin
      ];

      for (let c = 0; c < cells.length; c++) {
        if (c === 1) {
          for (let l = 0; l < wrappedProjectCode.length; l++) {
            doc.text(wrappedProjectCode[l], uX + 2, curY + 3.2 + (l * 2.5));
          }
        } else if (c === 2) {
          for (let l = 0; l < wrappedName.length; l++) {
            doc.text(wrappedName[l], uX + 2, curY + 3.2 + (l * 2.5));
          }
        } else {
          const verticalAdjustment = (rowHeight - 4.5) / 2;
          doc.text(cells[c], uX + 2, curY + 3.2 + verticalAdjustment);
        }
        uX += unassignedColWidths[c];
      }
      curY += rowHeight;

      if (curY > pageHeight - 30) break;
    }
  }



  return doc;
}

